"""Build per-trigger LaTeX tables for the AN in the Run 2 AN-19-273 Table 3 style.

For each (year, txbb_region, MC denominator), emit one compact table where:
  - rows: each jet HLT path plus a final "Combined (OR)" row
  - columns: per-era data efficiency + a single MC column
  - cells: 2-decimal efficiency values (no per-cell error bars)
  - leftmost header column is stacked "era / trigger"
The caption notes that statistical uncertainties are at the few-percent
level and refers back to Table~\\ref{tab:trig_sf} for the integrated SF.

Source data: per_era_efficiency_<year>_Inclusive_<region>_<mc>.csv
under sf_2d_<year>/output/<year>/Inclusive/<region>/<mc>/.

Output: a single file `per_trigger_tables.tex` under
   <an-dir>/sections/samples/
that contains every table back-to-back; trigger.tex pulls it in with one
\\input.

Usage:
    python3 make_per_trigger_tables.py --an-dir /path/to/HbbRun3_AN
"""
from __future__ import annotations
import argparse
import csv
import os
import sys
from collections import OrderedDict

YEARS = ["2022", "2022EE", "2023", "2023BPix", "2024"]
REGIONS = ["fail", "pass_bb", "pass_cc"]
MCS = ["ttbar", "qcd_muenriched"]

REGION_LABEL = {"fail": "fail", "pass_bb": "pass-bb", "pass_cc": "pass-cc"}
MC_LABEL = {"ttbar": r"\ttbar", "qcd_muenriched": r"QCD $\mu$-enriched"}


def _read_csv_as_dict(path):
    with open(path) as f:
        rows = list(csv.reader(f))
    header = rows[0]
    out = OrderedDict()
    for row in rows[1:]:
        trig = row[0]
        out[trig] = {col: float(val) for col, val in zip(header[1:], row[1:])}
    return header, out


def _latex_escape(s):
    return s.replace("_", r"\_")


def _format(eff):
    # Run 2 AN style: 2 decimal places, plain.
    return f"{eff:.2f}"


def build_table_for(year, region, mc, sf_dir):
    """Return LaTeX `table` env for (year, region, mc), or None if input missing."""
    base = os.path.join(
        sf_dir, f"sf_2d_{year}", "output", year, "Inclusive", region, mc
    )
    eff_path = os.path.join(
        base, f"per_era_efficiency_{year}_Inclusive_{region}_{mc}.csv"
    )
    if not os.path.exists(eff_path):
        return None

    eff_hdr, eff = _read_csv_as_dict(eff_path)
    eras_plus_mc = eff_hdr[1:]
    eras = [c for c in eras_plus_mc if c != "MC"]
    if "MC" not in eras_plus_mc:
        return None

    # Column spec: `l` for trigger column, `c` for each era + MC
    col_spec = "l" + "c" * (len(eras) + 1)
    era_header = " & ".join([r"era"] + eras + ["MC"]) + r" \\"
    trigger_header_row = r"trigger \\"

    body_lines = []
    for trig, eff_row in eff.items():
        cells = [_latex_escape(trig)]
        for e in eras:
            cells.append(_format(eff_row[e]))
        cells.append(_format(eff_row["MC"]))
        body_lines.append(" & ".join(cells) + r" \\")

    caption = (
        f"Trigger efficiency in data and simulation for the {year} "
        f"\\textit{{{REGION_LABEL[region]}}} region with the "
        f"{MC_LABEL[mc]} simulation denominator. "
        f"Trigger efficiencies are measured inclusively in the AK8 jet "
        f"kinematic region: $450 \\le \\pt < 1000$ GeV and "
        f"$40 \\le \\msd < 300$ GeV. "
        f"Statistical uncertainties on individual cells are at the few-percent "
        f"level; the lumi-weighted scale factor for this (year, region, "
        f"denominator) combination is given in Table~\\ref{{tab:trig_sf}}."
    )
    label = f"tab:trig_per_{year}_{region}_{mc}"

    tex = (
        "\\begin{table}[h]\n"
        "    \\centering\n"
        f"    \\begin{{tabular}}{{{col_spec}}}\n"
        "        \\hline\n"
        "        " + era_header + "\n"
        "        " + trigger_header_row + "\n"
        "        \\hline\n"
        + "\n".join("        " + line for line in body_lines) + "\n"
        "        \\hline\n"
        "    \\end{tabular}\n"
        f"    \\caption{{{caption}}}\n"
        f"    \\label{{{label}}}\n"
        "\\end{table}\n"
    )
    return tex


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sf-dir",
                    default=os.path.dirname(os.path.abspath(__file__)))
    ap.add_argument("--an-dir", required=True,
                    help="Path to HbbRun3_AN repo (LaTeX project root)")
    ap.add_argument("--out",
                    default="sections/samples/per_trigger_tables.tex",
                    help="Output file path under --an-dir")
    args = ap.parse_args()

    out_path = os.path.join(args.an_dir, args.out)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)

    lines = [
        "% Auto-generated by make_per_trigger_tables.py; do not edit by hand.",
        "% Re-run the generator after each fresh SF production round.",
        "",
    ]
    written = []
    missing = []
    for year in YEARS:
        for region in REGIONS:
            for mc in MCS:
                tex = build_table_for(year, region, mc, args.sf_dir)
                if tex is None:
                    missing.append((year, region, mc))
                    continue
                lines.append(tex)
                written.append((year, region, mc))

    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Wrote {len(written)} table(s) -> {out_path}")
    for y, r, m in written:
        print(f"  {y} / {r} / {m}")
    if missing:
        print(f"\n{len(missing)} table(s) missing CSV inputs (will appear on next run):")
        for y, r, m in missing:
            print(f"  - {y} / {r} / {m}")


if __name__ == "__main__":
    main()
